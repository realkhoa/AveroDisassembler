//! Report renderers: JSON (canonical), Markdown (readable/diffable), HTML (single file).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::ir::{Artifact, Evidence, Report, Severity};
use crate::util::{escape_html, human_size};

fn severity_upper(severity: Severity) -> &'static str {
    match severity {
        Severity::Critical => "CRITICAL",
        Severity::High => "HIGH",
        Severity::Medium => "MEDIUM",
        Severity::Low => "LOW",
        Severity::Info => "INFO",
    }
}

fn evidence_map(report: &Report) -> BTreeMap<&str, &Evidence> {
    report
        .artifact
        .evidence
        .iter()
        .map(|evidence| (evidence.id.as_str(), evidence))
        .collect()
}

fn imports_by_library(artifact: &Artifact) -> Vec<(String, Vec<String>)> {
    let mut grouped: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for import in &artifact.imports {
        let label = import
            .name
            .clone()
            .unwrap_or_else(|| format!("ordinal {}", import.ordinal.unwrap_or(0)));
        grouped
            .entry(import.library.clone())
            .or_default()
            .push(label);
    }
    grouped.into_iter().collect()
}

fn export_label(export: &crate::ir::Export) -> String {
    let name = export
        .name
        .clone()
        .unwrap_or_else(|| format!("ordinal {}", export.ordinal.unwrap_or(0)));
    match export.rva {
        Some(rva) => format!("{name} @ 0x{rva:x}"),
        None => name,
    }
}

pub fn to_json(report: &Report) -> String {
    serde_json::to_string_pretty(report)
        .unwrap_or_else(|error| format!("{{\"error\":\"failed to serialize report: {error}\"}}"))
}

/// Deterministic JSON: drops volatile fields so golden/CI comparisons are stable.
pub fn to_deterministic_json(report: &Report) -> String {
    let mut clone = report.clone();
    clone.generated_at = String::new();
    clone.artifact.path = None;
    serde_json::to_string_pretty(&clone).unwrap_or_default()
}

pub fn to_markdown(report: &Report) -> String {
    let artifact = &report.artifact;
    let evidence = evidence_map(report);
    let mut out = String::with_capacity(16 * 1024);
    let name = artifact
        .path
        .as_deref()
        .and_then(|path| Path::new(path).file_name())
        .map(|name| name.to_string_lossy().to_string())
        .unwrap_or_else(|| artifact.id.chars().take(16).collect());
    let arch = match (&artifact.architecture, artifact.bits) {
        (Some(arch), Some(bits)) => format!("{arch} / {bits}-bit"),
        (Some(arch), None) => arch.clone(),
        _ => "unknown".to_string(),
    };

    let _ = writeln!(out, "# Avero Report — {name}\n");
    let _ = writeln!(
        out,
        "> Generated by {} {} · IR {} · {}",
        report.tool.name, report.tool.version, report.tool.ir_version, report.generated_at
    );
    let _ = writeln!(
        out,
        "> Static, evidence-based analysis. Findings are candidates for manual review, not verdicts.\n"
    );

    // 1. Triage
    let _ = writeln!(out, "## 1. Triage\n");
    let _ = writeln!(out, "| Field | Value |");
    let _ = writeln!(out, "|---|---|");
    let _ = writeln!(
        out,
        "| File | `{}` |",
        artifact.path.as_deref().unwrap_or("(hidden)")
    );
    let _ = writeln!(
        out,
        "| Size | {} ({} bytes) |",
        human_size(artifact.size),
        artifact.size
    );
    let _ = writeln!(out, "| Kinds | {} |", artifact.kind_names());
    let _ = writeln!(out, "| Architecture | {arch} |");
    let _ = writeln!(out, "| Entropy | {:.4} bits/byte |", artifact.entropy);
    let _ = writeln!(
        out,
        "| SHA-256 | `{}` |",
        artifact.hashes.get("sha256").cloned().unwrap_or_default()
    );
    let _ = writeln!(
        out,
        "| MD5 | `{}` |",
        artifact.hashes.get("md5").cloned().unwrap_or_default()
    );
    let _ = writeln!(out, "| Sections | {} |", artifact.sections.len());
    let _ = writeln!(
        out,
        "| Imports / Exports | {} / {} |",
        artifact.imports.len(),
        artifact.exports.len()
    );
    let _ = writeln!(out, "| Strings | {} |", artifact.strings.len());
    let counts = crate::pipeline::severity_counts(report);
    let _ = writeln!(
        out,
        "| Findings | {} (critical {}, high {}, medium {}, low {}, info {}) |",
        report.findings.len(),
        counts.get("critical").copied().unwrap_or(0),
        counts.get("high").copied().unwrap_or(0),
        counts.get("medium").copied().unwrap_or(0),
        counts.get("low").copied().unwrap_or(0),
        counts.get("info").copied().unwrap_or(0)
    );
    let engines: Vec<String> = artifact
        .evidence
        .iter()
        .map(|evidence| format!("{} {}", evidence.producer.engine, evidence.producer.version))
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect();
    let _ = writeln!(
        out,
        "| Engines | {} |\n",
        if engines.is_empty() {
            "avero only".to_string()
        } else {
            engines.join(", ")
        }
    );

    // 2. Findings
    let _ = writeln!(out, "## 2. Findings ({})\n", report.findings.len());
    if report.findings.is_empty() {
        let _ = writeln!(
            out,
            "No findings from the analyzers that ran. See Coverage/Unknowns for limitations.\n"
        );
    }
    for (index, finding) in report.findings.iter().enumerate() {
        let _ = writeln!(
            out,
            "### {}. [{}] {}\n",
            index + 1,
            severity_upper(finding.severity),
            finding.title
        );
        let _ = writeln!(out, "{}\n", finding.detail);
        let _ = writeln!(
            out,
            "- **Category**: `{}` · **Confidence**: {}",
            finding.category, finding.confidence
        );
        if let Some(remediation) = &finding.remediation {
            let _ = writeln!(out, "- **Remediation**: {remediation}");
        }
        if !finding.evidence_ids.is_empty() {
            let _ = writeln!(out, "- **Evidence**:");
            for evidence_id in &finding.evidence_ids {
                if let Some(item) = evidence.get(evidence_id.as_str()) {
                    let _ = writeln!(
                        out,
                        "  - `{}` — {} {} / {}: {}",
                        item.id,
                        item.producer.engine,
                        item.producer.version,
                        item.kind,
                        item.excerpt
                            .clone()
                            .unwrap_or_else(|| format!("{:?}", item.locator))
                    );
                }
            }
        }
        let _ = writeln!(out);
    }

    // 3. Sections
    let _ = writeln!(out, "## 3. Sections\n");
    if artifact.sections.is_empty() {
        let _ = writeln!(out, "No section information.\n");
    } else {
        let _ = writeln!(
            out,
            "| Name | VA | VSize | Raw offset | Raw size | Entropy | Flags |"
        );
        let _ = writeln!(out, "|---|---:|---:|---:|---:|---:|---|");
        for section in &artifact.sections {
            let _ = writeln!(
                out,
                "| `{}` | 0x{:x} | 0x{:x} | 0x{:x} | 0x{:x} | {:.3} | {} |",
                section.name,
                section.va,
                section.vsize,
                section.raw_offset,
                section.raw_size,
                section.entropy,
                section.flags.join(", ")
            );
        }
        let _ = writeln!(out);
    }

    // 4. Imports
    let _ = writeln!(out, "## 4. Imports\n");
    let grouped = imports_by_library(artifact);
    if grouped.is_empty() {
        let _ = writeln!(out, "No import table.\n");
    } else {
        for (library, functions) in &grouped {
            let shown: Vec<&String> = functions.iter().take(25).collect();
            let _ = writeln!(
                out,
                "- **{}** ({}): {}{}",
                library,
                functions.len(),
                shown
                    .iter()
                    .map(|value| value.as_str())
                    .collect::<Vec<_>>()
                    .join(", "),
                if functions.len() > shown.len() {
                    format!(" … (+{} more)", functions.len() - shown.len())
                } else {
                    String::new()
                }
            );
        }
        let _ = writeln!(out);
    }

    // 5. Exports
    let _ = writeln!(out, "## 5. Exports ({})\n", artifact.exports.len());
    if artifact.exports.is_empty() {
        let _ = writeln!(out, "No exports.\n");
    } else {
        for export in artifact.exports.iter().take(100) {
            let _ = writeln!(out, "- {}", export_label(export));
        }
        let _ = writeln!(out);
    }

    // 6. Metadata
    let _ = writeln!(out, "## 6. Metadata\n");
    if artifact.metadata.is_empty() {
        let _ = writeln!(out, "No additional metadata.\n");
    } else {
        let _ = writeln!(out, "| Key | Value |");
        let _ = writeln!(out, "|---|---|");
        for (key, value) in artifact.metadata.iter().take(60) {
            let rendered = match value {
                serde_json::Value::String(text) => text.clone(),
                other => other.to_string(),
            };
            let _ = writeln!(out, "| `{key}` | {} |", rendered.replace('|', "\\|"));
        }
        let _ = writeln!(out);
    }

    // 7. Strings
    let _ = writeln!(
        out,
        "## 7. Strings ({} found, {} shown)\n",
        artifact.strings.len(),
        artifact.strings.len().min(100)
    );
    if artifact.strings.is_empty() {
        let _ = writeln!(out, "No strings found at the current threshold.\n");
    } else {
        let _ = writeln!(out, "```text");
        for entry in artifact.strings.iter().take(100) {
            let _ = writeln!(
                out,
                "0x{:08x}  {:<7} {}",
                entry.offset, entry.encoding, entry.value
            );
        }
        let _ = writeln!(out, "```");
        if artifact.strings.len() > 100 {
            let _ = writeln!(
                out,
                "\n> {} more strings — see `report.json` for the full list.",
                artifact.strings.len() - 100
            );
        }
        let _ = writeln!(out);
    }

    // 8. Coverage
    let _ = writeln!(out, "## 8. Coverage\n");
    let _ = writeln!(out, "| Analyzer | Status |");
    let _ = writeln!(out, "|---|---|");
    for (analyzer, status) in &report.coverage {
        let _ = writeln!(out, "| `{analyzer}` | {status} |");
    }
    let _ = writeln!(out);

    if !report.unknowns.is_empty() {
        let _ = writeln!(out, "## 9. Unknowns\n");
        for item in &report.unknowns {
            let _ = writeln!(out, "- {item}");
        }
        let _ = writeln!(out);
    }
    if !report.warnings.is_empty() {
        let _ = writeln!(out, "## 10. Warnings\n");
        for item in &report.warnings {
            let _ = writeln!(out, "- {item}");
        }
        let _ = writeln!(out);
    }

    let _ = writeln!(out, "## 11. Evidence index ({})\n", artifact.evidence.len());
    if artifact.evidence.is_empty() {
        let _ = writeln!(out, "No evidence.\n");
    } else {
        let _ = writeln!(out, "| ID | Engine | Kind | Locator | Excerpt | Conf |");
        let _ = writeln!(out, "|---|---|---|---|---|---:|");
        for item in artifact.evidence.iter().take(400) {
            let excerpt = item
                .excerpt
                .clone()
                .unwrap_or_else(|| format!("{:?}", item.locator));
            let _ = writeln!(
                out,
                "| `{}` | {} {} | {} | {} | {} | {} |",
                item.id,
                item.producer.engine,
                item.producer.version,
                item.kind,
                format!("{:?}", item.locator).replace('|', "\\|"),
                excerpt.replace('|', "\\|").replace('\n', " "),
                item.confidence
            );
        }
        if artifact.evidence.len() > 400 {
            let _ = writeln!(
                out,
                "\n> Showing only 400/{} evidence entries — see `report.json`.",
                artifact.evidence.len()
            );
        }
    }
    out
}

