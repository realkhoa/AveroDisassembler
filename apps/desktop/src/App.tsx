const MODE_KEY = "avero_desktop_mode";
const RECENT_KEY = "avero_desktop_recent";
const SEVERITIES: Severity[] = ["critical", "high", "medium", "low", "info"];

function sevClass(severity: string): string {
  return `severity sev-${severity}`;
}

function formatBytes(value: number): string {
  if (value < 1024) return `${value} B`;
  if (value < 1024 * 1024) return `${(value / 1024).toFixed(1)} KB`;
  return `${(value / (1024 * 1024)).toFixed(2)} MB`;
}

function shortHash(value?: string): string {
  return value ? `${value.slice(0, 12)}…` : "n/a";
}

function counts(findings: Finding[]): Record<Severity, number> {
  const result: Record<Severity, number> = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  for (const finding of findings) result[finding.severity] += 1;
  return result;
}

function fact<T>(report: Report | null, key: string): T | undefined {
  return report?.facts?.[key] as T | undefined;
}

function saveReport(report: Report): void {
  try {
    const serialized = JSON.stringify(report);
    if (serialized.length < 2_000_000) {
      localStorage.setItem(`avero_report_${report.artifact.id}`, serialized);
    }
  } catch {
    /* ignore quota */
  }
}

function loadStoredReport(id: string): Report | null {
  try {
    const raw = localStorage.getItem(`avero_report_${id}`);
    return raw ? (JSON.parse(raw) as Report) : null;
  } catch {
    return null;
  }
}

function recentReports(): RecentReport[] {
  try {
    return JSON.parse(localStorage.getItem(RECENT_KEY) || "[]") as RecentReport[];
  } catch {
    return [];
  }
}

function addRecent(report: Report): void {
  const severity = counts(report.findings);
  const entry: RecentReport = {
    id: report.artifact.id,
    name: report.artifact.path.split(/[/\\]/).pop() || report.artifact.id.slice(0, 12),
    size: report.artifact.size,
    kinds: report.artifact.kinds,
    severity: SEVERITIES.find((value) => severity[value] > 0) || "info",
    findings: report.findings.length,
    opened_at: new Date().toISOString(),
  };
  const rest = recentReports().filter((item) => item.id !== entry.id);
  localStorage.setItem(RECENT_KEY, JSON.stringify([entry, ...rest].slice(0, 12)));
}

