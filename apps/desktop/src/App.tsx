function HexView({ report, bytes, mode, apiUrl, onBytes }: { report: Report; bytes: Uint8Array | null; mode: Mode; apiUrl: string; onBytes: (bytes: Uint8Array) => void }) {
  const [offset, setOffset] = useState(0);
  const [data, setData] = useState<Uint8Array | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [jump, setJump] = useState("0");
  const input = useRef<HTMLInputElement>(null);
  const pageSize = 512;

  const load = useCallback(async (target: number) => {
    setError(null);
    try {
      if (mode === "API") {
        const slice = await api.getHex(apiUrl, report.artifact.id, target, pageSize);
        setData(slice);
      } else if (bytes) {
        setData(bytes.subarray(target, target + pageSize));
      } else {
        setData(null);
      }
    } catch (loadError: unknown) {
      setError(loadError instanceof Error ? loadError.message : "hex read failed");
    }
  }, [mode, apiUrl, report.artifact.id, bytes]);

  useEffect(() => { void load(offset); }, [load, offset]);

  const lines: string[] = [];
  if (data) {
    for (let index = 0; index < data.length; index += 16) {
      const chunk = Array.from(data.subarray(index, index + 16));
      const ascii = chunk.map((value) => (value >= 32 && value < 127 ? String.fromCharCode(value) : ".")).join("");
      lines.push(`${(offset + index).toString(16).padStart(8, "0")}  ${chunk.map((value) => value.toString(16).padStart(2, "0")).join(" ").padEnd(47)}  ${ascii}`);
    }
  }

  return (
    <div className="grid">
      <div className="card">
        <div className="row">
          <div className="field">
            <label>Offset (hex)</label>
            <input className="input mono" value={jump} onChange={(event) => setJump(event.target.value)} style={{ width: 140 }} />
          </div>
          <button className="button" onClick={() => { const parsed = parseInt(jump.replace(/^0x/, ""), 16); if (!Number.isNaN(parsed)) setOffset(Math.max(0, parsed)); }}>Go</button>
          <button className="button" disabled={offset === 0} onClick={() => setOffset(Math.max(0, offset - pageSize))}>Prev</button>
          <button className="button" onClick={() => setOffset(offset + pageSize)}>Next</button>
          {mode === "FILE" && !bytes && (
            <>
              <button className="button" onClick={() => input.current?.click()}>Attach artifact bytes</button>
              <input
                ref={input}
                type="file"
                style={{ display: "none" }}
                onChange={async (event) => {
                  const file = event.target.files?.[0];
                  if (file) onBytes(new Uint8Array(await file.arrayBuffer()));
                  event.target.value = "";
                }}
              />
            </>
          )}
          <span className="muted small">report size {formatBytes(report.artifact.size)} · page {pageSize} B</span>
        </div>
        {error && <div className="alert error mt">{error}</div>}
      </div>
      <div className="card" style={{ padding: 0 }}>
        {!data && mode === "FILE" && !bytes ? (
          <div className="muted small" style={{ padding: 16 }}>Attach the original artifact to inspect bytes (the report contains metadata only).</div>
        ) : (
          <pre className="pre" style={{ margin: 0, border: 0, maxHeight: "68vh" }}>{lines.join("\n")}</pre>
        )}
      </div>
    </div>
  );
}

