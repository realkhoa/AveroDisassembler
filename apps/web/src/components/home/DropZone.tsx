"use client";

/**
 * @file DropZone.tsx
 * @brief Interactive drag-and-drop file ingestion zone for Avero report.json files.
 */

import React, { useState, useRef } from "react";
import { useRouter } from "next/navigation";
import { UploadCloud, FileText, AlertCircle, Sparkles } from "lucide-react";
import { useReport } from "@/lib/report-context";
import { getDataSource } from "@/lib/data-source";

/**
 * @brief DropZone component accepting report.json uploads.
 */
export function DropZone() {
  const router = useRouter();
  const { setActiveReport, loadSampleReport } = useReport();
  const [isDragging, setIsDragging] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const fileInputRef = useRef<HTMLInputElement>(null);

  /**
   * @brief Ingests file content and routes to overview on success.
   * @param file User-selected or dropped file.
   */
  const handleFile = async (file: File) => {
    setErrorMsg(null);
    setIsLoading(true);

    try {
      const content = await file.text();
      const dataSource = getDataSource();
      const report = await dataSource.loadReport(content);
      setActiveReport(report);
      router.push(`/report/${report.artifact.id}/overview`);
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : "Failed to parse report file";
      setErrorMsg(`Invalid report format: ${message}`);
    } finally {
      setIsLoading(false);
    }
  };

  const handleDragOver = (e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(true);
  };

  const handleDragLeave = () => {
    setIsDragging(false);
  };

  const handleDrop = async (e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(false);

    if (e.dataTransfer.files && e.dataTransfer.files.length > 0) {
      await handleFile(e.dataTransfer.files[0]);
    }
  };

  const handleSampleClick = async () => {
    setIsLoading(true);
    setErrorMsg(null);
    try {
      const report = await loadSampleReport();
      router.push(`/report/${report.artifact.id}/overview`);
    } catch (err: unknown) {
      setErrorMsg(err instanceof Error ? err.message : "Failed to load sample report");
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="w-full max-w-2xl mx-auto space-y-4">
      <div
        onDragOver={handleDragOver}
        onDragLeave={handleDragLeave}
        onDrop={handleDrop}
        onClick={() => fileInputRef.current?.click()}
        className={`border-2 border-dashed rounded-card p-10 flex flex-col items-center justify-center text-center cursor-pointer transition-all ${
          isDragging
            ? "border-accent bg-accent/5 scale-[1.01]"
            : "border-border hover:border-muted bg-panel/50 hover:bg-panel"
        }`}
      >
        <input
          ref={fileInputRef}
          type="file"
          accept=".json,application/json"
          className="hidden"
          onChange={(e) => {
            if (e.target.files && e.target.files.length > 0) {
              handleFile(e.target.files[0]);
            }
          }}
        />

        <div className="w-14 h-14 rounded-full bg-panel-2 border border-border flex items-center justify-center text-accent mb-4">
          <UploadCloud className="w-7 h-7" />
        </div>

        <h3 className="text-base font-semibold text-text mb-1">
          Drop your <span className="font-mono text-accent">report.json</span> here
        </h3>
        <p className="text-xs text-muted max-w-sm mb-4">
          Supports reports generated by <code className="text-accent bg-bg px-1.5 py-0.5 rounded">avero scan &lt;file&gt; --json</code>.
          Local analysis only, files never leave your machine.
        </p>

        <button
          type="button"
          disabled={isLoading}
          className="px-4 py-2 rounded-input bg-panel-2 hover:bg-border text-xs font-medium text-text border border-border transition-colors"
        >
          {isLoading ? "Parsing report..." : "Browse Files"}
        </button>
      </div>

      {errorMsg && (
        <div className="flex items-center space-x-2 p-3 rounded-input bg-critical/10 border border-critical/30 text-critical text-xs">
          <AlertCircle className="w-4 h-4 shrink-0" />
          <span>{errorMsg}</span>
        </div>
      )}

      {/* Quick sample report launcher */}
      <div className="flex items-center justify-between p-3 rounded-card bg-panel border border-border">
        <div className="flex items-center space-x-2 text-xs">
          <Sparkles className="w-4 h-4 text-accent" />
          <span>Don&apos;t have a report yet? Explore with the sample APK report:</span>
        </div>
        <button
          onClick={handleSampleClick}
          disabled={isLoading}
          className="flex items-center space-x-1.5 px-3 py-1.5 rounded-input bg-accent/10 hover:bg-accent/20 text-accent text-xs font-semibold border border-accent/30 transition-colors"
        >
          <FileText className="w-3.5 h-3.5" />
          <span>Open Sample Report</span>
        </button>
      </div>
    </div>
  );
}
